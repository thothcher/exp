// Writes a small multi-chapter PDF for testing: node scripts/make-sample-pdf.mjs [out.pdf] [chapters]
import fs from 'node:fs';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const out = process.argv[2] || 'sample-book.pdf';
const chapters = Number(process.argv[3]) || 4;
const doc = await PDFDocument.create();
const font = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);

function page(title, lines, number) {
  const p = doc.addPage([420, 595]);
  let y = 540;
  if (title) {
    p.drawText(title, { x: 40, y, size: 20, font: bold, color: rgb(0.1, 0.2, 0.2) });
    y -= 40;
  }
  for (const line of lines) {
    p.drawText(line, { x: 40, y, size: 11, font, color: rgb(0.1, 0.1, 0.1), maxWidth: 340 });
    y -= 18;
  }
  if (number) p.drawText(String(number), { x: 205, y: 28, size: 10, font });
}

page('Sample Book of Learning', ['A test document generated by Folio.', 'Author: Test Author', 'First edition, 2026'], null);
let n = 1;
for (let c = 1; c <= chapters; c++) {
  for (let i = 0; i < 10; i++) {
    const title = i === 0 ? `Chapter ${c}: Topic number ${c}` : '';
    page(title, [
      `Section ${c}.${i + 1}. Learning happens through repeated, spaced practice.`,
      'A stimulus that is paired with a reward becomes a signal for that reward.',
      'Habits form when a cue reliably leads to a routine and a result.',
      `This is page ${n} of the sample book, in chapter ${c}.`,
    ], n);
    n += 1;
  }
}
fs.writeFileSync(out, await doc.save());
console.log(`${out}: ${doc.getPageCount()} pages`);
